// 辅助函数：根据公司名或 logo 获取渲染内容（支持 SVG 或原生 Emoji/字符）
export function renderCompanyLogo(logoOrName) {
  if (!logoOrName) return '🏢'
  if (logoOrName.startsWith('<svg')) return logoOrName
  
  // 匹配是否是知名大厂
  const found = FAMOUS_COMPANIES.find(c => c.name === logoOrName || c.id === logoOrName)
  if (found) return found.svg
  return logoOrName
}
